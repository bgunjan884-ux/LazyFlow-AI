
const taskInput = document.getElementById("taskInput");
const generateBtn = document.getElementById("generateBtn");
const modelName = document.getElementById("modelName");

const resultText = document.getElementById("resultText");
const resultHeading = document.getElementById("resultHeading");
const emptyState = document.getElementById("emptyState");
const loading = document.getElementById("loading");

const copyBtn = document.getElementById("copyBtn");
const clearBtn = document.getElementById("clearBtn");
const modeNote = document.getElementById("modeNote");
const connectionStatus = document.getElementById("connectionStatus");

let currentRequest = 0;

// Fill the input using example prompts.
document.querySelectorAll(".chip").forEach((button) => {
  button.addEventListener("click", () => {
    taskInput.value = button.dataset.prompt;
    taskInput.focus();
  });
});

// Display a result on the page.
function showResult(text, heading, note) {
  resultHeading.textContent = heading;
  resultText.textContent = text;

  resultText.classList.remove("hidden");
  emptyState.classList.add("hidden");

  copyBtn.disabled = false;
  modeNote.textContent = note;
}

// Demo responses: these are templates, not AI-generated answers.
function makeDemoResponse(task) {
  const text = task.toLowerCase();

  if (
    text.includes("todo") ||
    text.includes("to-do") ||
    text.includes("notes") ||
    text.includes("priorit")
  ) {
    return `YOUR SIMPLE TO-DO PLAN

1. Start with the task due soonest.
2. Group small tasks together.
3. Leave non-urgent tasks for later.

TIP:
Choose just one next step.
You do not have to do everything at once. 🦥`;
  }

  if (
    text.includes("reminder") ||
    text.includes("message") ||
    text.includes("email") ||
    text.includes("write")
  ) {
    return `YOUR MESSAGE DRAFT

Hi! Just checking in on this when
you get a chance. Could you please
send me an update?

No rush if you are busy.
Thank you!

You can edit this draft before sending.`;
  }

  if (
    text.includes("relax") ||
    text.includes("evening") ||
    text.includes("rest") ||
    text.includes("calm")
  ) {
    return `YOUR SLOW EVENING 🌿

1. Take a break from your screen.
2. Get some water or a warm drink.
3. Listen to music or read something.
4. Leave non-urgent tasks for tomorrow.

Rest is allowed. No productivity
points required. 🦥`;
  }

  return `LET'S MAKE THIS EASIER

1. Break your task into small steps.
2. Decide what "good enough" means.
3. Start with just 10 minutes.
4. Take a break and review your progress.

YOUR REQUEST:
${task}

This is a sample response.
Connect a local AI model for real AI answers.`;
}

// Ask a locally running Ollama model.
async function askLocalAI(task, requestId) {
  const model = modelName.value.trim() || "llama3.2";

  const response = await fetch(
    "http://localhost:11434/api/generate",
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        model: model,
        prompt:
          "You are LazyFlow AI, a calm and practical assistant. " +
          "Help the user save effort. Give concise, useful answers. " +
          "Break tasks into simple steps when helpful. " +
          "Never claim you accessed files or messages unless provided. " +
          "User request: " + task,
        stream: false
      })
    }
  );

  if (!response.ok) {
    throw new Error("Ollama could not process the request.");
  }

  const data = await response.json();

  if (requestId !== currentRequest) return;

  if (!data.response) {
    throw new Error("The model returned an empty response.");
  }

  connectionStatus.textContent = "Local AI connected";

  showResult(
    data.response.trim(),
    "Done at your pace.",
    "Response generated by your local Ollama model."
  );
}

// Main button.
async function generate() {
  const task = taskInput.value.trim();

  if (!task) {
    taskInput.focus();
    modeNote.textContent =
      "Please enter a task or choose one of the example prompts.";
    return;
  }

  const requestId = ++currentRequest;

  generateBtn.disabled = true;
  loading.classList.remove("hidden");
  emptyState.classList.add("hidden");
  resultText.classList.add("hidden");
  copyBtn.disabled = true;

  try {
    await askLocalAI(task, requestId);
  } catch (error) {
    if (requestId !== currentRequest) return;

    connectionStatus.textContent = "Demo mode";

    showResult(
      makeDemoResponse(task),
      "Here is a little shortcut.",
      "Demo response only. For real AI, install Ollama, download " +
      "a compatible model, and configure local browser access."
    );
  } finally {
    if (requestId === currentRequest) {
      loading.classList.add("hidden");
      generateBtn.disabled = false;
    }
  }
}

generateBtn.addEventListener("click", generate);

// Ctrl + Enter also generates a response.
taskInput.addEventListener("keydown", (event) => {
  if (
    (event.ctrlKey || event.metaKey) &&
    event.key === "Enter"
  ) {
    generate();
  }
});

// Copy the generated result.
copyBtn.addEventListener("click", async () => {
  try {
    await navigator.clipboard.writeText(resultText.textContent);

    copyBtn.textContent = "Copied!";
    setTimeout(() => {
      copyBtn.textContent = "Copy result";
    }, 1500);
  } catch (error) {
    modeNote.textContent =
      "Clipboard access was blocked. Select the result text and copy it manually.";
  }
});

// Clear the input and result.
clearBtn.addEventListener("click", () => {
  currentRequest++;

  taskInput.value = "";
  resultText.textContent = "";

  resultText.classList.add("hidden");
  loading.classList.add("hidden");
  emptyState.classList.remove("hidden");

  resultHeading.textContent = "A little less effort.";
  modeNote.textContent =
    "Your text stays in this page unless you send it to your local model.";

  copyBtn.disabled = true;
  generateBtn.disabled = false;
  copyBtn.textContent = "Copy result";

  taskInput.focus();
});
